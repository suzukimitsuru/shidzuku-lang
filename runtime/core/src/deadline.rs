//! 期限の判定。
//!
//! 期限を測るのは動作環境である(第4章 4.1・4.3)。意味の核は時計を持たず、
//! 器が経過時間計で読んだ値(ナノ秒)を受け取って、残りを判定するだけである。

/// 期限までの残り。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 残り {
    /// 期限が `none` である。
    無期限,
    /// 期限まであと何ナノ秒か。
    あと(u64),
    /// 期限を過ぎた。
    過ぎた,
}

/// 始めた時の読み `始め` と今の読み `今`(どちらも経過時間計のナノ秒)から、期限 `期限`(ナノ秒、`None` は無期限)までの残りを測る。
pub fn 残りを測る(始め: u64, 今: u64, 期限: Option<u64>) -> 残り {
    match 期限 {
        None => 残り::無期限,
        Some(期限) => {
            let 経った = 今.saturating_sub(始め);
            if 経った >= 期限 { 残り::過ぎた } else { 残り::あと(期限 - 経った) }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 期限の前と後() {
        assert_eq!(残りを測る(100, 150, Some(100)), 残り::あと(50));
        assert_eq!(残りを測る(100, 200, Some(100)), 残り::過ぎた);
        assert_eq!(残りを測る(100, 900, None), 残り::無期限);
    }
}
